#!/usr/bin/env node
// Bakes the kombify rosette (brand master, never recoloured) into an LVGL
// ARGB8888 image at the exact pixel size a display profile needs, so the
// device never scales the mark at runtime.
//
//   node firmware/tools/gen_rosette.mjs [size ...]   default: 104 124 167 186 (classic: all boards; watch: RLCD, 1.85C, C6)
//
// Source: firmware/components/kbx_ui/assets/src/kombify_rosette.png (kombify-Brand
// kombify-rosette-dark). Downscaling is an exact area average in
// premultiplied alpha, so the coloured edges keep their hue and no dark fringe
// appears on the dark ground. Output: components/kbx_ui/assets/kombify_rosette_<size>.c and
// components/kbx_ui/assets/kombify_rosette.h. Pure Node (zlib), no npm packages.
import { readFileSync, writeFileSync } from "node:fs";
import { inflateSync } from "node:zlib";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const assets = join(here, "..", "components", "kbx_ui", "assets");
const sizes = process.argv.slice(2).map(Number).filter((n) => n > 0);
if (!sizes.length) sizes.push(104, 124, 167, 186);

function decodePng(buf) {
  if (buf.readUInt32BE(0) !== 0x89504e47) throw new Error("not a PNG");
  let off = 8, w = 0, h = 0, depth = 0, ctype = 0, interlace = 0;
  const idat = [];
  while (off < buf.length) {
    const len = buf.readUInt32BE(off);
    const type = buf.toString("ascii", off + 4, off + 8);
    const data = buf.subarray(off + 8, off + 8 + len);
    if (type === "IHDR") {
      w = data.readUInt32BE(0); h = data.readUInt32BE(4);
      depth = data[8]; ctype = data[9]; interlace = data[12];
    } else if (type === "IDAT") idat.push(data);
    off += 12 + len;
  }
  if (depth !== 8 || ctype !== 6 || interlace) throw new Error("need 8-bit RGBA non-interlaced PNG");
  const raw = inflateSync(Buffer.concat(idat));
  const bpp = 4, stride = w * bpp, out = Buffer.alloc(w * h * bpp);
  for (let y = 0; y < h; y++) {
    const f = raw[y * (stride + 1)];
    const line = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? out[y * stride + x - bpp] : 0;
      const b = y ? out[(y - 1) * stride + x] : 0;
      const c = x >= bpp && y ? out[(y - 1) * stride + x - bpp] : 0;
      let v = line[x];
      if (f === 1) v += a;
      else if (f === 2) v += b;
      else if (f === 3) v += (a + b) >> 1;
      else if (f === 4) {
        const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
        v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
      }
      out[y * stride + x] = v & 0xff;
    }
  }
  return { w, h, px: out };
}

// Area-average resample of the source (fit into size x size, centred).
function resample(src, size) {
  const scale = Math.max(src.w, src.h) / size;
  const ox = (size - src.w / scale) / 2, oy = (size - src.h / scale) / 2;
  const out = Buffer.alloc(size * size * 4);
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const sx0 = (x - ox) * scale, sx1 = (x + 1 - ox) * scale;
      const sy0 = (y - oy) * scale, sy1 = (y + 1 - oy) * scale;
      let r = 0, g = 0, b = 0, a = 0;
      for (let sy = Math.max(0, Math.floor(sy0)); sy < Math.min(src.h, Math.ceil(sy1)); sy++) {
        const wy = Math.min(sy + 1, sy1) - Math.max(sy, sy0);
        for (let sx = Math.max(0, Math.floor(sx0)); sx < Math.min(src.w, Math.ceil(sx1)); sx++) {
          const wx = Math.min(sx + 1, sx1) - Math.max(sx, sx0);
          const i = (sy * src.w + sx) * 4, al = src.px[i + 3] / 255, wgt = wx * wy;
          r += src.px[i] * al * wgt; g += src.px[i + 1] * al * wgt; b += src.px[i + 2] * al * wgt;
          a += al * wgt;
        }
      }
      const area = scale * scale, o = (y * size + x) * 4;
      const A = a / area;
      // LVGL ARGB8888 byte order: B, G, R, A (straight alpha).
      out[o + 0] = a ? Math.round(b / a) : 0;
      out[o + 1] = a ? Math.round(g / a) : 0;
      out[o + 2] = a ? Math.round(r / a) : 0;
      out[o + 3] = Math.round(Math.min(1, A) * 255);
    }
  }
  return out;
}

const src = decodePng(readFileSync(join(assets, "src", "kombify_rosette.png")));
const banner = "/* GENERATED by firmware/tools/gen_rosette.mjs from assets/src/kombify_rosette.png - do not edit. */\n";
for (const size of sizes) {
  const px = resample(src, size);
  let rows = "";
  for (let y = 0; y < size; y++) {
    rows += "    " + [...px.subarray(y * size * 4, (y + 1) * size * 4)].join(",") + ",\n";
  }
  writeFileSync(join(assets, `kombify_rosette_${size}.c`), banner +
    `#define LV_LVGL_H_INCLUDE_SIMPLE 1\n#include "lvgl.h"\n#include "kombify_rosette.h"\n\n` +
    `static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t kombify_rosette_${size}_map[] = {\n${rows}};\n\n` +
    `const lv_image_dsc_t kombify_rosette_${size} = {\n` +
    `    .header = {\n        .magic = LV_IMAGE_HEADER_MAGIC,\n        .cf = LV_COLOR_FORMAT_ARGB8888,\n` +
    `        .w = ${size},\n        .h = ${size},\n        .stride = ${size * 4},\n    },\n` +
    `    .data_size = sizeof(kombify_rosette_${size}_map),\n    .data = kombify_rosette_${size}_map,\n};\n`);
}
writeFileSync(join(assets, "kombify_rosette.h"), banner +
  "/* kombify rosette, the brand mark at the orb's centre. Full colour, never\n" +
  " * recoloured or filtered (brand book); only its opacity may change. One\n" +
  " * pre-baked size per display profile, no runtime scaling of the mark. */\n" +
  "#pragma once\n#include \"lvgl.h\"\n\n" +
  sizes.map((s) => `extern const lv_image_dsc_t kombify_rosette_${s};\n`).join(""));
console.log(`wrote kombify_rosette_{${sizes.join(",")}}.c + kombify_rosette.h from ${src.w}x${src.h}`);
