#!/usr/bin/env node
// Bakes the Aura Orb's outer glow (the radial lead-colour falloff of
// aura_orb.c `bake_glow`, without the core's outer shadow) into a small LVGL
// A8 alpha map for the boards without PSRAM (C6 AMOLED): the map is shown
// scaled up with the state's lead colour as image recolour, so the glow costs
// 9 KB of flash and no RAM.
//
//   node firmware/tools/gen_orb_glow.mjs [size]   default: 96
//
// Output: components/kbx_ui/assets/kbx_orb_glow.c and kbx_orb_glow.h.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const assets = join(here, "..", "components", "kbx_ui", "assets");
const size = Number(process.argv[2]) || 96;

// CSS stand-in of the mockup glow: radial lead .42 -> 0 at 68% of the
// farthest-corner radius, with a 4x4 ordered dither against 8-bit banding.
const BAYER4 = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];
const R = size / 2, fc = R * Math.SQRT2;
const px = Buffer.alloc(size * size);
for (let y = 0; y < size; y++) {
  for (let x = 0; x < size; x++) {
    const r = Math.hypot(x + 0.5 - R, y + 0.5 - R);
    let a = 0.42 * (1 - r / (0.68 * fc));
    if (a < 0) a = 0;
    const d = (BAYER4[(y & 3) * 4 + (x & 3)] + 0.5) / 16 - 0.5;
    px[y * size + x] = a <= 0 ? 0 : Math.max(0, Math.min(255, Math.round(a * 255 + d * 1.5)));
  }
}
const banner = "/* GENERATED by firmware/tools/gen_orb_glow.mjs - do not edit. */\n";
let rows = "";
for (let y = 0; y < size; y++) rows += "    " + [...px.subarray(y * size, (y + 1) * size)].join(",") + ",\n";
writeFileSync(join(assets, "kbx_orb_glow.c"), banner +
  `#define LV_LVGL_H_INCLUDE_SIMPLE 1\n#include "lvgl.h"\n#include "kbx_orb_glow.h"\n\n` +
  `static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t kbx_orb_glow_map[] = {\n${rows}};\n\n` +
  `const lv_image_dsc_t kbx_orb_glow = {\n` +
  `    .header = {\n        .magic = LV_IMAGE_HEADER_MAGIC,\n        .cf = LV_COLOR_FORMAT_A8,\n` +
  `        .w = ${size},\n        .h = ${size},\n        .stride = ${size},\n    },\n` +
  `    .data_size = sizeof(kbx_orb_glow_map),\n    .data = kbx_orb_glow_map,\n};\n`);
writeFileSync(join(assets, "kbx_orb_glow.h"), banner +
  "/* The orb's outer glow as an A8 map of the glow box (1.28 x the orb\n" +
  " * diameter); recolour it with the state's lead colour and scale it up. */\n" +
  "#pragma once\n#include \"lvgl.h\"\n\n" +
  "extern const lv_image_dsc_t kbx_orb_glow;\n");
console.log(`wrote kbx_orb_glow.c + kbx_orb_glow.h (${size}x${size} A8)`);
