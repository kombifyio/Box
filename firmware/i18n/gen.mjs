#!/usr/bin/env node
// Generates the Box display string tables (and optionally the LVGL font
// subsets) from firmware/i18n/messages.json.
//
//   node firmware/i18n/gen.mjs            -> components/kbx_core/include/i18n_ids.h,
//                                            components/kbx_core/i18n_table.c
//   node firmware/i18n/gen.mjs --fonts    -> also components/kbx_ui/assets/fonts/kbx_*.c
//
// --fonts installs lv_font_conv and the OFL source fonts (Montserrat, Noto Sans
// SC, Noto Sans Arabic) into a temp dir at the pinned versions below, then runs
// exactly the lv_font_conv commands printed to stdout. Only the glyphs the
// strings need are embedded (--symbols), so adding or changing a translation
// means: edit messages.json, rerun with --fonts, commit the generated files.
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, existsSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const coreDir = join(here, "..", "components", "kbx_core");
const uiDir = join(here, "..", "components", "kbx_ui");
const src = JSON.parse(readFileSync(join(here, "messages.json"), "utf8"));
const ids = Object.keys(src.messages);

// Locales rendered on the device. hi is deliberately absent: LVGL's text
// engine cannot shape Devanagari (no conjuncts, no pre-base i-matra), so the
// device falls back to English for hi. Its strings stay in messages.json.
const DEVICE = [
  ["EN", "en"],
  ["DE", "de"],
  ["ES", "es"],
  ["ZH_HANS", "zh-Hans"],
  ["AR", "ar"],
];

for (const id of ids) {
  for (const loc of src.locales) {
    if (typeof src.messages[id][loc] !== "string" || !src.messages[id][loc]) {
      throw new Error(`${id}: missing ${loc}`);
    }
  }
  const pcts = (s) => (s.match(/%d/g) || []).length;
  for (const loc of src.locales) {
    if (pcts(src.messages[id][loc]) !== pcts(src.messages[id].en)) {
      throw new Error(`${id}: %d count differs in ${loc}`);
    }
  }
}

const banner = "/* GENERATED by firmware/i18n/gen.mjs from firmware/i18n/messages.json - do not edit. */\n";
writeFileSync(
  join(coreDir, "include", "i18n_ids.h"),
  banner +
    "#pragma once\n\ntypedef enum {\n" +
    ids.map((id) => `    I18N_${id},`).join("\n") +
    "\n    I18N__COUNT\n} i18n_id_t;\n",
);

const cstr = (s) => JSON.stringify(s); // JSON escapes are valid C escapes for our strings (no control chars)
let table = banner + '#include "i18n.h"\n\n';
for (const [sym, loc] of DEVICE) {
  table += `const char *const kbx_i18n_${sym}[I18N__COUNT] = {\n`;
  for (const id of ids) table += `    [I18N_${id}] = ${cstr(src.messages[id][loc])},\n`;
  table += "};\n\n";
}
writeFileSync(join(coreDir, "i18n_table.c"), table);
console.log(`wrote i18n_ids.h + i18n_table.c (${ids.length} ids x ${DEVICE.length} device locales)`);

if (!process.argv.includes("--fonts")) process.exit(0);

const chars = (loc) => new Set([...ids.map((id) => src.messages[id][loc]).join("")]);
const nonAscii = (set) => [...set].filter((c) => c.codePointAt(0) > 0x7f);
// Always cover the full de/es letter set so a new translation rarely needs a font change.
const latin = new Set([..."äöüßÄÖÜáéíóúÁÉÍÓÚñÑ¿¡", ...nonAscii(chars("de")), ...nonAscii(chars("es"))]);
const zh = new Set(nonAscii(chars("zh-Hans")));
const sym = (set) => [...set].sort((a, b) => a.codePointAt(0) - b.codePointAt(0)).join("");

const work = mkdtempSync(join(tmpdir(), "kbx-fonts-"));
const npm = process.platform === "win32" ? "npm.cmd" : "npm";
const pins = [
  "lv_font_conv@1.5.3",
  "@expo-google-fonts/montserrat@0.4.2",
  "@expo-google-fonts/noto-sans-sc@0.4.3",
  "@expo-google-fonts/noto-sans-arabic@0.4.3",
];
const install = spawnSync(npm, ["install", "--prefix", work, ...pins], { stdio: "inherit", shell: process.platform === "win32" });
if (install.status !== 0) process.exit(install.status ?? 1);

const font = (pkg, file) => join(work, "node_modules", "@expo-google-fonts", pkg, file.split("_")[1], `${file}.ttf`);
const faces = {
  lat: { ttf: font("montserrat", "Montserrat_500Medium"), select: ["--symbols", sym(latin)] },
  zh: { ttf: font("noto-sans-sc", "NotoSansSC_400Regular"), select: ["--symbols", sym(zh)] },
  // LVGL's Arabic shaper rewrites letters to Presentation Forms-B (FE70-FEFC),
  // so those forms plus the base letters, harakat, question mark and the
  // ellipsis must exist in the font.
  ar: { ttf: font("noto-sans-arabic", "NotoSansArabic_400Regular"), select: ["-r", "0x61F,0x621-0x652,0x2026,0xFE70-0xFEFC"] },
};
// UI 2 type ramp for the S size class: 14 small,
// 16 body/pills, 18 captions and titles, 20 the error line. 4 bpp, kerning kept,
// rendered at size (labels are never scaled). ASCII and LV_SYMBOL glyphs come
// from LVGL's built-in Montserrat of the same size (sdkconfig.defaults).
const RAMP = [14, 16, 18, 20];
const outDir = join(uiDir, "assets", "fonts");
mkdirSync(outDir, { recursive: true });
const conv = join(work, "node_modules", "lv_font_conv", "lv_font_conv.js");
for (const size of RAMP) {
  for (const [name, f] of Object.entries(faces)) {
    if (!existsSync(f.ttf)) throw new Error(`missing font file ${f.ttf}`);
    const out = join(outDir, `kbx_${name}_${size}.c`);
    const args = [conv, "--font", f.ttf, ...f.select, "--size", String(size), "--bpp", "4", "--no-compress",
      "--format", "lvgl", "--lv-fallback", `lv_font_montserrat_${size}`, "--lv-font-name", `kbx_${name}_${size}`, "-o", out];
    console.log("node", args.map((a) => (/[\s]/.test(a) ? JSON.stringify(a) : a)).join(" "));
    const r = spawnSync(process.execPath, args, { stdio: "inherit" });
    if (r.status !== 0) process.exit(r.status ?? 1);
    // LVGL include shortcut on the ESP-IDF include path.
    const body = readFileSync(out, "utf8");
    writeFileSync(out, "#define LV_LVGL_H_INCLUDE_SIMPLE 1\n" + body.replace(/\r\n/g, "\n").replace(/^ \* Opts: .*$/m, ` * Opts: see firmware/i18n/gen.mjs (kbx_${name}_${size})`));
  }
}

// Large Latin caption face for the wide RLCD voice scene (28 px, readable
// from across the room); other scripts keep the 20 px ramp there.
{
  const f = faces.lat;
  const out = join(outDir, "kbx_lat_28.c");
  const args = [conv, "--font", f.ttf, ...f.select, "--size", "28", "--bpp", "4", "--no-compress",
    "--format", "lvgl", "--lv-fallback", "lv_font_montserrat_28", "--lv-font-name", "kbx_lat_28", "-o", out];
  console.log("node", args.map((a) => (/[\s]/.test(a) ? JSON.stringify(a) : a)).join(" "));
  const r = spawnSync(process.execPath, args, { stdio: "inherit" });
  if (r.status !== 0) process.exit(r.status ?? 1);
  const body = readFileSync(out, "utf8");
  writeFileSync(out, "#define LV_LVGL_H_INCLUDE_SIMPLE 1\n" + body.replace(/\r\n/g, "\n").replace(/^ \* Opts: .*$/m, " * Opts: see firmware/i18n/gen.mjs (kbx_lat_28)"));
}

// Home numerals for the 1-bit RLCD (clock, temperature, humidity): Montserrat
// SemiBold, because light strokes break up when thresholded to one bit.
for (const [name, size, symbols] of [["kbx_home_96", 96, "0123456789:"], ["kbx_home_44", 44, "0123456789.,-°% C"]]) {
  const ttf = font("montserrat", "Montserrat_600SemiBold");
  if (!existsSync(ttf)) throw new Error(`missing font file ${ttf}`);
  const out = join(outDir, `${name}.c`);
  const args = [conv, "--font", ttf, "--symbols", symbols, "--size", String(size), "--bpp", "4", "--no-compress",
    "--format", "lvgl", "--lv-font-name", name, "-o", out];
  console.log("node", args.map((a) => (/[\s]/.test(a) ? JSON.stringify(a) : a)).join(" "));
  const r = spawnSync(process.execPath, args, { stdio: "inherit" });
  if (r.status !== 0) process.exit(r.status ?? 1);
  const body = readFileSync(out, "utf8");
  writeFileSync(out, "#define LV_LVGL_H_INCLUDE_SIMPLE 1\n" + body.replace(/\r\n/g, "\n").replace(/^ \* Opts: .*$/m, ` * Opts: see firmware/i18n/gen.mjs (${name})`));
}

// Display numerals (update percentage, R-10): Montserrat Light, digits only.
{
  const ttf = font("montserrat", "Montserrat_300Light");
  if (!existsSync(ttf)) throw new Error(`missing font file ${ttf}`);
  const out = join(outDir, "kbx_num_56.c");
  const args = [conv, "--font", ttf, "--symbols", "0123456789 %:.", "--size", "56", "--bpp", "4", "--no-compress",
    "--format", "lvgl", "--lv-font-name", "kbx_num_56", "-o", out];
  console.log("node", args.join(" "));
  const r = spawnSync(process.execPath, args, { stdio: "inherit" });
  if (r.status !== 0) process.exit(r.status ?? 1);
  const body = readFileSync(out, "utf8");
  writeFileSync(out, "#define LV_LVGL_H_INCLUDE_SIMPLE 1\n" + body.replace(/\r\n/g, "\n").replace(/^ \* Opts: .*$/m, " * Opts: see firmware/i18n/gen.mjs (kbx_num_56)"));
}
